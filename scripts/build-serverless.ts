#!/usr/bin/env tsx
// Bundle the Express server into a single ESM file for Vercel serverless.
//
// The frontend and the server share code (schema, prompts, verification), and
// Vercel functions cannot import from outside `api/`. esbuild inlines that
// shared code into one deployable file.
//
// Usage: npx tsx scripts/build-serverless.ts
//
// Run this after changing anything under server/ or the shared frontend/lib
// files, otherwise api/index.js drifts from the source of truth.
import { build } from "esbuild";
import path from "node:path";

const ROOT = process.cwd();

await build({
  entryPoints: [path.join(ROOT, "server/index.ts")],
  outfile: path.join(ROOT, "api/index.js"),
  bundle: true,
  platform: "node",
  target: "node22",
  format: "esm",
  splitting: false,
  minify: false,
  sourcemap: false,
  banner: {
    js: "// Generated by scripts/build-serverless.ts — do not edit by hand.\n// Source of truth: server/ and frontend/src/lib/.",
  },
  // Vercel provides these; bundling them breaks the runtime.
  external: ["express", "cors", "dotenv", "multer", "zod", "pdf-parse"],
  logLevel: "info",
});

console.log("wrote api/index.js");
